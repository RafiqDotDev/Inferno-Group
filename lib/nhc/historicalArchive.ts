/**
 * Returns recent historical storms filtered by basin (optional)
 */
export function getRecentHistoricalStorms(basin?: string): DetailedStorm[] {
  if (!basin || basin === "all") {
    return RECENT_HISTORICAL_STORMS;
  }
  const normalized = basin.toUpperCase();
  if (normalized === "ATLC" || normalized === "AL") {
    return RECENT_HISTORICAL_STORMS.filter((s) => s.basin === "AL");
  }
  if (normalized === "EPAC" || normalized === "EP") {
    return RECENT_HISTORICAL_STORMS.filter((s) => s.basin === "EP");
  }
  return RECENT_HISTORICAL_STORMS;
}

/**
 * Finds a historical storm by ID or name
 */
export function getHistoricalStormById(idOrName: string): DetailedStorm | null {
  const query = idOrName.toLowerCase();
  return (
    RECENT_HISTORICAL_STORMS.find(
      (s) =>
        s.id.toLowerCase() === query ||
        s.name.toLowerCase() === query ||
        s.id.toLowerCase().includes(query) ||
        query.includes(s.name.toLowerCase())
    ) || null
  );
}

